const STORAGE_KEY = 'cssd_theme'

const CSS_KEYS = [
  ['brand', 'brand'],
  ['brandDark', 'brand-dark'],
  ['brandSoft', 'brand-soft'],
  ['brandMist', 'brand-mist'],
  ['asideFrom', 'aside-from'],
  ['asideMid', 'aside-mid'],
  ['asideTo', 'aside-to'],
  ['paper', 'paper'],
  ['ink', 'ink'],
  ['muted', 'muted'],
  ['stationFrom', 'station-from'],
  ['stationTo', 'station-to'],
  ['elPrimary', 'el-color-primary'],
  ['elDark2', 'el-color-primary-dark-2'],
  ['elLight3', 'el-color-primary-light-3'],
  ['elLight5', 'el-color-primary-light-5'],
  ['elLight7', 'el-color-primary-light-7'],
  ['elLight8', 'el-color-primary-light-8'],
  ['elLight9', 'el-color-primary-light-9']
]

export function getThemeId() {
  return localStorage.getItem(STORAGE_KEY) || 'teal'
}

export function getTheme(id = getThemeId()) {
  return THEMES.find((t) => t.id === id) || THEMES[0]
}

export function applyTheme(id) {
  const theme = getTheme(id)
  const root = document.documentElement
  const v = theme.vars
  for (const [key, css] of CSS_KEYS) {
    root.style.setProperty(`--${css}`, v[key])
  }
  root.dataset.theme = theme.id
  localStorage.setItem(STORAGE_KEY, theme.id)
  return theme
}

export function initTheme() {
  return applyTheme(getThemeId())
}
