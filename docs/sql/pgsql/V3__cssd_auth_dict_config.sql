-- 登录账号、单号序列、字典、系统参数、打印模板（一期种子）
CREATE TABLE IF NOT EXISTS cssd.cssd_auth_account (
    id                  varchar(36)     NOT NULL,
    staff_id            varchar(36)     NOT NULL,
    staff_no            varchar(32)     NOT NULL,
    password_hash       varchar(200)    NOT NULL,
    created_at          timestamptz     NOT NULL DEFAULT now(),
    created_by          varchar(36)     NULL,
    created_by_no       varchar(32)     NULL,
    created_by_name     varchar(64)     NULL,
    updated_at          timestamptz     NOT NULL DEFAULT now(),
    updated_by          varchar(36)     NULL,
    updated_by_no       varchar(32)     NULL,
    updated_by_name     varchar(64)     NULL,
    is_deleted          smallint        NOT NULL DEFAULT 0,
    deleted_at          timestamptz     NULL,
    deleted_by          varchar(36)     NULL,
    deleted_by_no       varchar(32)     NULL,
    deleted_by_name     varchar(64)     NULL,
    create_channel      varchar(16)     NULL,
    update_channel      varchar(16)     NULL,
    delete_channel      varchar(16)     NULL,
    CONSTRAINT pk_cssd_auth_account PRIMARY KEY (id)
);
COMMENT ON TABLE cssd.cssd_auth_account IS '登录账号（密码不进人员快照）';
CREATE UNIQUE INDEX IF NOT EXISTS uk_cssd_auth_staff ON cssd.cssd_auth_account (staff_id) WHERE is_deleted = 0;
CREATE UNIQUE INDEX IF NOT EXISTS uk_cssd_auth_no ON cssd.cssd_auth_account (staff_no) WHERE is_deleted = 0;

CREATE TABLE IF NOT EXISTS cssd.cssd_bill_seq (
    prefix              varchar(8)      NOT NULL,
    biz_date            varchar(8)      NOT NULL,
    next_no             integer         NOT NULL,
    CONSTRAINT pk_cssd_bill_seq PRIMARY KEY (prefix, biz_date)
);
COMMENT ON TABLE cssd.cssd_bill_seq IS '业务单号日流水';

